const CASES = textRoleCases();
const missing = Object.entries(SAMPLED_TEXT).flatMap(([role, texts]) =>
  texts
    .filter((text) => !CASES.some((one) => one.role === role && one.text === text))
    .map((text) => `${role}: ${text}`),
);
if (missing.length !== 0) {
  throw new Error(`Missing authored text fixtures: ${missing.join("; ")}`);
}
const SAMPLED_CASES = CASES.filter(({ role, text }) => SAMPLED_TEXT[role]?.includes(text) ?? true);

// Text never shrinks to fit: each role has one size, and sampled strings fit its room
// on no more than its lines.
describe("every text role", () => {
  it.each(SAMPLED_CASES.map(({ overflow, role, text }) => [`${role}: ${text}`, overflow] as const))(
    "fits %s",
    (_name, overflow) => {
      expect(overflow).toBe("");
    },
  );
});
