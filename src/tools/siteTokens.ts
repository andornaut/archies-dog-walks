import palette from "../../shared/palette.json" with { type: "json" };
import { BUTTON_FACE_EDGE, BUTTON_LIP_PX, BUTTON_SIZE } from "../data/index.ts";
import {
  ACTION_LABEL_SCALE,
  CARD_PANEL,
  cssHex,
  MODAL,
  PALETTE,
  PAPER_PANEL,
  TEXT_SCALE,
  TOP_BAR_FACE,
  topBarGlyphRect,
} from "../ui/index.ts";

// art: the display face's (Silkscreen's) font box, its ascender and descender, and its capitals'
// ink, 5 of its 8-pixel em, standing on the baseline, in em.
const DISPLAY_FONT = { ascent: 1.03, cap: 0.625, descent: 0.25 } as const;

// Where npm run export:data writes the site's design tokens, relative to the repository root.
export const SITE_TOKENS_PATH = "public/tokens.css";

const px = (value: number) => `${value}px`;
const colours = <T extends Record<string, keyof typeof PALETTE>>(names: T) =>
  Object.fromEntries(Object.entries(names).map(([role, name]) => [role, cssHex(PALETTE[name])]));

// The site's tokens by name: the house palette, the game's standard button and icon control
// geometry, and the paper and card panel recipes (src/ui/paperPanel.ts).
export function siteTokens(): Map<string, string> {
  const glyph = topBarGlyphRect({ x: 0, y: 0 });
  const paper = colours(PAPER_PANEL.colours);
  const card = colours(CARD_PANEL.colours);
  const tokens: [string, string][] = [
    ...Object.entries(palette).map(([name, { hex }]): [string, string] => [
      `palette-${name}`,
      `#${hex}`,
    ]),
    ["action-label-ratio", String(ACTION_LABEL_SCALE / TEXT_SCALE)],
    // A text button's ink outline, the lit row under its top outline, and its lip.
    ["button-bevel", px(BUTTON_FACE_EDGE.top - BUTTON_FACE_EDGE.bottom)],
    ["button-border", px(BUTTON_FACE_EDGE.bottom)],
    ["button-gap", px(BUTTON_SIZE.gap)],
    ["button-height", px(BUTTON_SIZE.compact.height)],
    // A label sized to its content keeps the modal's inset from the face's outer edge.
    ["button-inset", px(MODAL.pad - BUTTON_FACE_EDGE.bottom)],
    ["button-lip", px(BUTTON_LIP_PX)],
    ["button-press", px(BUTTON_SIZE.press)],
    ["button-stack-gap", px(BUTTON_SIZE.stackGap)],
    ["button-wide-width", px(BUTTON_SIZE.wide.width)],
    ["button-width", px(BUTTON_SIZE.compact.width)],
    ["card-corner", px(CARD_PANEL.corner)],
    ["card-fill", card.fill!],
    ["card-inner", card.inner!],
    ["card-inner-width", px(CARD_PANEL.inner)],
    ["card-lip", card.lip!],
    ["card-lip-width", px(CARD_PANEL.lip)],
    ["card-line", card.line!],
    ["card-line-width", px(CARD_PANEL.line)],
    ["card-text", card.text!],
    // How far the display face's capitals' middle sits below its font box's: a line box centres
    // the ascender and descender.
    [
      "display-ink-drop",
      `${((DISPLAY_FONT.ascent - DISPLAY_FONT.descent - DISPLAY_FONT.cap) / 2).toFixed(4)}em`,
    ],
    // An icon control's face and its glyph's place on it, as the top bar draws them.
    ["icon-face", px(TOP_BAR_FACE.size)],
    ["icon-glyph", px(BUTTON_SIZE.icon.glyph)],
    ["icon-glyph-x", px(glyph.x)],
    ["icon-glyph-y", px(glyph.y)],
    // The face's lip, under its fill and over its bottom outline.
    ["icon-lip", px(TOP_BAR_FACE.size - TOP_BAR_FACE.fill.y - TOP_BAR_FACE.fill.height - 1)],
    ["paper-bevel", paper.bevel!],
    ["paper-bevel-height", px(PAPER_PANEL.bevel)],
    ["paper-border", paper.border!],
    ["paper-border-width", px(PAPER_PANEL.border)],
    ["paper-fill", paper.fill!],
    ["paper-lip", paper.lip!],
    ["paper-lip-height", px(PAPER_PANEL.lip)],
    ["paper-shadow", paper.shadow!],
    ["paper-shadow-offset", px(PAPER_PANEL.shadow)],
    ["paper-text", paper.text!],
  ];
  return new Map(tokens.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

// public/tokens.css: every token as a custom property on the root.
export function siteTokensCss(): string {
  const lines = [...siteTokens()].map(([name, value]) => `  --${name}: ${value};`);
  return [
    "/* Generated by npm run export:data from shared/palette.json and the game's button and panel",
    "   geometry (src/tools/siteTokens.ts). Change those, not this file. */",
    ":root {",
    ...lines,
    "}",
    "",
  ].join("\n");
}
